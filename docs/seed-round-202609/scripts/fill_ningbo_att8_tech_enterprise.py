def style_run(run, size_pt: int = 12) -> None:
    run.font.size = Pt(size_pt)
    run.font.name = "Times New Roman"
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn("w:eastAsia"), "宋体")


def insert_after(paragraph: Paragraph, text: str) -> None:
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    np = Paragraph(new_p, paragraph._parent)
    pf = np.paragraph_format
    pf.first_line_indent = Pt(24)
    pf.line_spacing = 1.5
    pf.space_after = Pt(8)
    for i, block in enumerate(text.split("\n")):
        if i:
            np.add_run("\n")
        run = np.add_run(block)
        style_run(run, 12)
    ppr = np._p.get_or_add_pPr()
    jc = OxmlElement("w:jc")
    jc.set(qn("w:val"), "both")
    ppr.append(jc)


def fill(src: Path, dest: Path) -> None:
    doc = Document(str(src))
    hits = []
    for para in doc.paragraphs:
        key = para.text.strip()
        if key in BODY:
            hits.append((para, key))
    if len(hits) != len(BODY):
        found = {k for _, k in hits}
        missing = [k for k in BODY if k not in found]
        raise SystemExit(f"prompt mismatch, missing: {missing}")
    for para, key in reversed(hits):
        insert_after(para, BODY[key])
    dest.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(dest))


def main() -> None:
    if not SRC.exists():
        raise SystemExit(f"missing template: {SRC}")
    dests = [
        DESK / OUT_NAME,
        KEEP / OUT_NAME,
    ]
    first = dests[0]
    fill(SRC, first)
    for dest in dests[1:]:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(first.read_bytes())
    print("wrote", first)
    for d in dests[1:]:
        print("copy", d)


if __name__ == "__main__":
    main()
