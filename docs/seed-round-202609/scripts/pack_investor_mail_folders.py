def write_mail(inst: dict, dest: Path, files: dict[str, bytes]) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    attach = dest / "附件"
    attach.mkdir(exist_ok=True)
    how_lines = [
        f"机构：{inst['folder']}",
        f"怎么发：{inst['how']}",
        f"收件人：{inst['to']}",
        f"抄送：{inst['cc']}",
        f"官网：{inst['site']}",
    ]
    if inst.get("phone"):
        how_lines.append(f"电话：{inst['phone']}")
    how_lines += [
        "",
        "附件加本文件夹「附件」里的三份：一页纸、备忘录、路演 PDF。",
        "不要发 pptx（体积大、对方电脑可能乱码）。",
        "不要把产品演示视频当附件；有成片后用飞书/网盘链接。",
        "不要附投递清单或资金评估。",
    ]
    (dest / "00-怎么发.txt").write_text("\n".join(how_lines) + "\n", encoding="utf-8")
    (dest / "邮件主题与正文.txt").write_text(
        "主题\n"
        + inst["subject"]
        + "\n\n正文\n"
        + inst["body"].rstrip()
        + "\n",
        encoding="utf-8",
    )
    (attach / "1-一页纸-执行摘要.docx").write_bytes(files["onepager"])
    (attach / "2-投资人备忘录.docx").write_bytes(files["memo"])
    (attach / "3-路演PPT.pdf").write_bytes(files["deck"])


def main() -> None:
    if not ONEPAGER.exists() or not MEMO.exists() or not DECK_PDF.exists():
        raise SystemExit("missing one-pager, memo, or deck pdf")
    DESK.mkdir(parents=True, exist_ok=True)
    (DESK / "00-哪些要发邮件.txt").write_text(INDEX, encoding="utf-8")
    files = {
        "onepager": ONEPAGER.read_bytes(),
        "memo": MEMO.read_bytes(),
        "deck": DECK_PDF.read_bytes(),
    }
    for inst in INSTITUTIONS:
        write_mail(inst, DESK / inst["group"] / inst["folder"], files)
        print(inst["group"], inst["folder"], flush=True)
    print("DESK", DESK)


if __name__ == "__main__":
    main()
