function parseDramaStoryAi(raw: string): {
  story: string
  roles?: string
  conflict?: string
  dialogue?: string
} | null {
  const text = String(raw || '').trim()
  if (!text) return null
  const fence = text.match(/```(?:json)?\s*([\s\S]*?)```/i)
  const jsonStr = (fence?.[1] || text).trim()
  const start = jsonStr.indexOf('{')
  const end = jsonStr.lastIndexOf('}')
  if (start >= 0 && end > start) {
    try {
      const o = JSON.parse(jsonStr.slice(start, end + 1)) as Record<string, unknown>
      const story = String(o.story ?? o['一句话故事'] ?? '').trim()
      if (story) {
        const roles = String(o.roles ?? o['角色'] ?? o['人设'] ?? '').trim()
        const conflict = String(o.conflict ?? o['核心冲突'] ?? '').trim()
        const dialogue = String(o.dialogue ?? o['对白钩子'] ?? o['对白'] ?? '').trim()
        return {
          story,
          ...(roles ? { roles } : {}),
          ...(conflict ? { conflict } : {}),
          ...(dialogue ? { dialogue } : {}),
        }
      }
    } catch {
      /* fall through to plain text */
    }
  }
  const first = text
    .split('\n')
    .map((s) => s.trim())
    .find((s) => s && !s.startsWith('{') && !s.startsWith('```'))
  return first ? { story: first.replace(/^["「]|["」]$/g, '') } : null
}

function parseDramaCharacterPortraitAi(raw: string): string | null {
  const text = String(raw || '').trim()
  if (!text) return null
  const fence = text.match(/```(?:json)?\s*([\s\S]*?)```/i)
  const jsonStr = (fence?.[1] || text).trim()
  const start = jsonStr.indexOf('{')
  const end = jsonStr.lastIndexOf('}')
  if (start >= 0 && end > start) {
    try {
      const o = JSON.parse(jsonStr.slice(start, end + 1)) as Record<string, unknown>
      const portrait = String(
        o.portrait ?? o.character ?? o.desc ?? o.description ?? o['角色形象'] ?? o['画像'] ?? '',
      ).trim()
      if (portrait) return portrait.replace(/^["「]|["」]$/g, '')
    } catch {
      /* fall through to plain text */
    }
  }
  const cleaned = text
    .replace(/^```(?:json)?\s*/i, '')
    .replace(/\s*```$/i, '')
    .trim()
  if (!cleaned || cleaned.startsWith('{')) return null
  return cleaned.replace(/^["「]|["」]$/g, '').trim() || null
}

