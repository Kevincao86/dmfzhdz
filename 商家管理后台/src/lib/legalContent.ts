import type { HelpManualEdition } from './helpManualTypes'
import { LEGAL_COMPANY_NAME, productNameForEdition } from './legalProductMeta'

export type LegalSection = { title: string; paragraphs: string[] }

export function buildPrivacySections(edition: HelpManualEdition): LegalSection[] {
  const product = productNameForEdition(edition)
  const company = LEGAL_COMPANY_NAME
  return [
    {
      title: '引言',
      paragraphs: [
        `感谢您访问${company}运营的${product}（以下简称「我们」或「本平台」）。我们非常重视用户（下称「您」）的隐私和个人信息安全，并将按照法律法规要求采取相应安全保护措施。`,
        `本隐私政策适用于${product}提供的全部功能与服务。请您在使用各项功能或服务前仔细阅读并充分理解本政策；若您不同意，请停止使用相关服务。`,
        `本政策不适用于由其他第三方向您提供的服务；您在使用第三方服务前应了解其隐私政策。`,
      ],
    },
    {
      title: '一、我们如何收集和使用您的个人信息',
      paragraphs: [
        '为向您提供账号注册与登录、业务管理、订单与招募协作、AI 辅助、在线客服及安全运营等服务，我们可能收集：账号信息（登录名、手机号、密码哈希、微信 OpenID 等）、商户/机构资料、门店与商品信息、招募与履约数据、您主动上传的内容、设备与日志信息（IP、操作日志、设备标识等）。',
        'AI 相关功能可能处理您输入的文本、图片或业务描述以生成建议内容；此类内容仅用于向您提供服务，我们不会将其用于与本服务无关的目的，法律法规另有规定的除外。',
        '在征得您同意或法律法规允许的范围内，我们可能向您发送与服务相关的通知或调研信息；您可按提示退订营销类信息。',
      ],
    },
    {
      title: '二、我们如何共享、转让与公开披露',
      paragraphs: [
        '我们不会向无关第三方出售您的个人信息。仅在以下情形可能共享：经您明确同意；为完成交易或履约所必需的合作伙伴（如云基础设施、短信、支付）；法律法规或监管要求；合并、收购或破产清算时依法转移。',
        '我们要求接收方按照本政策及相关法律法规处理个人信息，并采取合理的安全措施。',
      ],
    },
    {
      title: '三、存储与保护',
      paragraphs: [
        '您的个人信息原则上存储于中华人民共和国境内。我们采用加密传输、访问控制、审计与备份等措施保护数据安全。',
        '我们仅在实现目的所必需的期限内保留您的信息；超出期限后将删除或匿名化处理，法律法规另有规定的除外。',
      ],
    },
    {
      title: '四、您的权利',
      paragraphs: [
        '您有权访问、更正、删除您的个人信息，撤回授权同意，注销账号，以及获取个人信息副本（法律法规另有规定的除外）。',
        '您可通过平台「设置」或联系客服行使上述权利；我们将在合理期限内响应您的请求。',
      ],
    },
    {
      title: '五、未成年人保护',
      paragraphs: [
        '本平台主要面向具有完全民事行为能力的商户、服务商及从业者。若您为未成年人，请在监护人指导下使用并在取得监护人同意后提供个人信息。',
      ],
    },
    {
      title: '六、政策更新与联系我们',
      paragraphs: [
        '我们可能适时修订本政策，修订版本将在平台公布并注明生效日期。重大变更将以显著方式提示。',
        `如您对本政策有任何疑问，请通过${product}内在线客服或平台公示的联系方式与${company}联系。`,
        `发布与生效日期：2026年6月7日 · ${company}`,
      ],
    },
  ]
}

